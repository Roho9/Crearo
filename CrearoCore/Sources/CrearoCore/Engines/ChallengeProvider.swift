/// The authored campaign. The original twelve positions never move, preserving existing saves.
/// After the full bank, content repeats while the player's level and stable content ID stay clear.
public enum ChallengeProvider {
    public static var catalogCount: Int { chapters.count }

    /// Canonical first-pass content, with content IDs instead of day IDs. For a playable attempt
    /// always use `challenge(level:date:)`, which stamps the current calendar day.
    public static var allContent: [DailyChallenge] { chapters }

    public static func dayKey(_ date: Date = Date(), timeZone: TimeZone = .current) -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.calendar = Calendar(identifier: .gregorian)
        formatter.timeZone = timeZone
        formatter.dateFormat = "yyyy-MM-dd"
        return formatter.string(from: date)
    }

    public static func challenge(level: Int, date: Date = Date()) -> DailyChallenge {
        let number = max(1, level)
        let chapter = chapters[(number - 1) % chapters.count]
        return DailyChallenge(id: dayKey(date), level: number, title: chapter.title,
                              setup: chapter.setup, goal: chapter.goal, question: chapter.question,
                              placeholder: chapter.placeholder, focusDimension: chapter.focusDimension,
                              contentID: chapter.contentID, region: chapter.region, obstacle: chapter.obstacle,
                              constraint: chapter.constraint, hint: chapter.hint,
                              revisionPrompt: chapter.revisionPrompt, practiceContext: chapter.practiceContext,
                              regionIndex: chapter.regionIndex, sceneTarget: chapter.sceneTarget)
    }

    private static func authored(_ contentID: String, title: String, setup: String, goal: String,
                                 question: String, placeholder: String, focus: CreativeDimension,
                                 region: ChallengeRegion = .prism, index: Int,
                                 obstacle: ChallengeObstacle, sceneTarget: String? = nil,
                                 constraint: String, hint: String, revision: String,
                                 goalTerms: [String], mechanismTerms: [String],
                                 minimumIdeas: Int = 1) -> DailyChallenge {
        DailyChallenge(id: contentID, level: region.firstLevel + index - 1,
                       title: title, setup: setup, goal: goal, question: question,
                       placeholder: placeholder, focusDimension: focus, contentID: contentID,
                       region: region, obstacle: obstacle, constraint: constraint, hint: hint,
                       revisionPrompt: revision,
                       practiceContext: PracticeChallengeContext(goal: goal, goalTerms: goalTerms,
                                                                mechanismTerms: mechanismTerms,
                                                                minimumDistinctIdeas: minimumIdeas),
                       regionIndex: index, sceneTarget: sceneTarget)
    }

